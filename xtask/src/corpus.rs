use serde::{Deserialize, Serialize};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

type R<T> = Result<T, String>;

/* ------------------------------------------------------------- lockfile */

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct Lock {
    pub version: u32,
    #[serde(default, rename = "source")]
    pub sources: Vec<Source>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Source {
    /// Short stable name; also the cache subdirectory.
    pub id: String,
    pub url: String,
    pub sha256: String,
    pub bytes: u64,
    /// SPDX identifier where one applies. Recorded for provenance only: this
    /// repository redistributes none of these bytes, it records how to obtain
    /// them. A source whose terms forbid redistribution is therefore still
    /// fine to reference here, but must never be committed or published.
    pub license: String,
    /// Which population this source stands in for. These are reported
    /// separately, never pooled, because they are different questions:
    ///
    ///   `apps`      third-party application content, what a user actually
    ///               compresses. Tier A stands in for /Applications, using
    ///               permissively-licensed apps and toolchains.
    ///   `system`    macOS system content: dyld caches, ICU and locale
    ///               tables, model assets. The ipsw case, and where LZBITMAP's
    ///               fixed-stride structure is supposed to win. Tier B, built
    ///               from an IPSW and never distributed.
    ///   `reference` neither, included so results are comparable to
    ///               published numbers elsewhere.
    pub population: String,
    #[serde(default)]
    pub note: String,
}

fn repo_root() -> PathBuf {
    // CARGO_MANIFEST_DIR is <root>/xtask
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask has a parent")
        .to_path_buf()
}

fn lock_path() -> PathBuf {
    repo_root().join("corpus/oss.lock.toml")
}
fn cache_dir() -> PathBuf {
    repo_root().join("corpus/cache")
}
fn segments_dir() -> PathBuf {
    repo_root().join("corpus/segments")
}
fn manifest_path() -> PathBuf {
    repo_root().join("corpus/manifest.tsv")
}

fn load_lock() -> R<Lock> {
    let p = lock_path();
    if !p.exists() {
        return Ok(Lock { version: 1, sources: vec![] });
    }
    let text = fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))?;
    toml::from_str(&text).map_err(|e| format!("{}: {e}", p.display()))
}

fn save_lock(lock: &Lock) -> R<()> {
    let text = toml::to_string_pretty(lock).map_err(|e| e.to_string())?;
    let p = lock_path();
    fs::create_dir_all(p.parent().unwrap()).map_err(|e| e.to_string())?;
    fs::write(&p, format!("# Generated by `cargo run -p xtask -- corpus add`.\n\
                           # No content from these sources is committed or redistributed.\n\n{text}"))
        .map_err(|e| format!("{}: {e}", p.display()))
}

/* ---------------------------------------------------------------- shell */

fn run(cmd: &str, args: &[&str]) -> R<String> {
    let out = Command::new(cmd)
        .args(args)
        .output()
        .map_err(|e| format!("{cmd}: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "{cmd} {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

fn sha256(path: &Path) -> R<String> {
    let out = run("shasum", &["-a", "256", &path.to_string_lossy()])?;
    Ok(out.split_whitespace().next().unwrap_or_default().to_string())
}

fn download(url: &str, dest: &Path) -> R<()> {
    fs::create_dir_all(dest.parent().unwrap()).map_err(|e| e.to_string())?;
    run("curl", &["-fSL", "--retry", "3", "-o", &dest.to_string_lossy(), url])?;
    Ok(())
}

/// Unpack into `dest`. Archive handling is delegated to the system tools:
/// `tar` on macOS and modern Linux reads gz/xz/bz2/zst transparently.
fn extract(archive: &Path, dest: &Path) -> R<()> {
    fs::create_dir_all(dest).map_err(|e| e.to_string())?;
    let name = archive.to_string_lossy().to_lowercase();
    let a = archive.to_string_lossy().to_string();
    let d = dest.to_string_lossy().to_string();
    // Downloads are cached under the bare source id, so sniff the magic too:
    // macOS bsdtar reads zip, GNU tar does not.
    let mut magic = [0u8; 4];
    let is_zip = fs::File::open(archive)
        .and_then(|mut f| std::io::Read::read_exact(&mut f, &mut magic))
        .is_ok_and(|_| magic == *b"PK\x03\x04");
    if name.ends_with(".zip") || is_zip {
        run("unzip", &["-qq", "-o", &a, "-d", &d]).map(|_| ())?;
    } else if name.ends_with(".dmg") {
        return Err("dmg sources need manual extraction; prefer a tar or zip artifact".into());
    } else {
        run("tar", &["-xf", &a, "-C", &d]).map(|_| ())?;
    }
    strip_exec_bits(dest)
}

/// Corpus files are only ever read as bytes, never run. Some upstream
/// archives (app bundles in particular) ship executable Mach-O binaries and
/// shell scripts; leaving those +x serves no purpose here and just makes an
/// accidental double-click or `./` do something. Directories keep their
/// mode: traversal needs the execute bit on those.
fn strip_exec_bits(root: &Path) -> R<()> {
    use std::os::unix::fs::PermissionsExt;
    fn walk(dir: &Path) -> R<()> {
        for entry in fs::read_dir(dir).map_err(|e| e.to_string())? {
            let entry = entry.map_err(|e| e.to_string())?;
            let path = entry.path();
            let meta = entry.metadata().map_err(|e| e.to_string())?;
            if meta.is_dir() {
                walk(&path)?;
            } else if meta.is_file() {
                let mut perm = meta.permissions();
                let mode = perm.mode() & !0o111;
                perm.set_mode(mode);
                fs::set_permissions(&path, perm).map_err(|e| e.to_string())?;
            }
        }
        Ok(())
    }
    walk(root)
}

/* ------------------------------------------------------------ arg parse */

fn flag<'a>(args: &'a [String], name: &str) -> Option<&'a str> {
    let i = args.iter().position(|a| a == name)?;
    args.get(i + 1).map(|s| s.as_str())
}
fn has(args: &[String], name: &str) -> bool {
    args.iter().any(|a| a == name)
}
fn num(args: &[String], name: &str, default: u64) -> R<u64> {
    match flag(args, name) {
        None => Ok(default),
        Some(v) => v
            .replace('_', "")
            .parse()
            .map_err(|_| format!("{name}: not a number: {v}")),
    }
}

/* --------------------------------------------------------------- add */

pub fn add(args: &[String]) -> R<()> {
    let url = args
        .first()
        .filter(|a| !a.starts_with("--"))
        .ok_or("usage: corpus add <url> [--id ID] ...")?;

    let id = flag(args, "--id")
        .map(str::to_string)
        .unwrap_or_else(|| {
            url.rsplit('/')
                .next()
                .unwrap_or("source")
                .split(['.', '?'])
                .next()
                .unwrap_or("source")
                .to_string()
        });

    let mut lock = load_lock()?;
    if lock.sources.iter().any(|s| s.id == id) {
        return Err(format!("id already locked: {id} (remove it first to re-add)"));
    }

    let tmp = cache_dir().join("downloads").join(&id);
    eprintln!("fetching {url}");
    download(url, &tmp)?;
    let digest = sha256(&tmp)?;
    let bytes = fs::metadata(&tmp).map_err(|e| e.to_string())?.len();

    lock.version = 1;
    lock.sources.push(Source {
        id: id.clone(),
        url: url.to_string(),
        sha256: digest.clone(),
        bytes,
        license: flag(args, "--license").unwrap_or("UNKNOWN").to_string(),
        population: flag(args, "--population").unwrap_or("general").to_string(),
        note: flag(args, "--note").unwrap_or_default().to_string(),
    });
    lock.sources.sort_by(|a, b| a.id.cmp(&b.id));
    save_lock(&lock)?;
    eprintln!("locked {id}  {bytes} bytes  sha256 {digest}");
    Ok(())
}

/* -------------------------------------------------------------- fetch */

pub fn fetch(_args: &[String]) -> R<()> {
    let lock = load_lock()?;
    if lock.sources.is_empty() {
        return Err("nothing locked yet: use `corpus add <url>` first".into());
    }
    for s in &lock.sources {
        let dl = cache_dir().join("downloads").join(&s.id);
        // `.noindex`: some sources are macOS .app bundles (e.g. Electron
        // apps kept as realistic corpus population). A plain "unpacked"
        // name lets Spotlight index them, which auto-registers them with
        // Launch Services: Dock icon, "Open With" entries, even default
        // handler for file types they claim. The `.noindex` suffix is
        // Apple's documented convention for excluding a subtree from
        // Spotlight metadata indexing, which starves that registration
        // path entirely.
        let unpacked = cache_dir().join("unpacked.noindex").join(&s.id);

        if dl.exists() && sha256(&dl)? == s.sha256 {
            eprintln!("{:<20} cached", s.id);
        } else if unpacked.join(".mirror-complete").exists() {
            eprintln!("{:<20} cached (mirror)", s.id);
            continue;
        } else {
            eprintln!("{:<20} downloading", s.id);
            if let Err(e) = download(&s.url, &dl) {
                // Upstream unreachable (cloud VMs reach little beyond GitHub):
                // rebuild the same tree from a pinned mirror instead.
                eprintln!("{:<20} unreachable, using mirror", s.id);
                let _ = fs::remove_file(&dl);
                let script = repo_root().join("corpus/fetch-mirrors.sh");
                run("bash", &[&script.to_string_lossy(), &cache_dir().to_string_lossy(), &s.id])
                    .map_err(|m| format!("{e}\n{m}"))?;
                continue;
            }
            let got = sha256(&dl)?;
            if got != s.sha256 {
                return Err(format!(
                    "{}: hash mismatch\n  locked {}\n  got    {}\n\
                     Upstream changed the artifact at this URL. Do not silently \
                     re-lock: a moved artifact means published numbers no longer \
                     refer to the same bytes.",
                    s.id, s.sha256, got
                ));
            }
        }

        if !unpacked.exists() {
            eprintln!("{:<20} extracting", s.id);
            extract(&dl, &unpacked)?;
        }
    }
    eprintln!("\n{} sources ready in {}", lock.sources.len(), cache_dir().display());
    Ok(())
}

/* -------------------------------------------------------------- build */

/// Routed into the small `precompressed` kind rather than the main corpus,
/// and reported separately. NOT a claim that these hold nothing, that is
/// what the measurement is for, and it has already been surprising:
///
///     zip  35.42% saved     png  11.47%     jpg  1.65%
///
/// Container formats are here precisely because their compressibility is a
/// property of what is inside them, not of the extension. A .dmg is UDZO or
/// UDBZ (compressed) or UDRO/UDRW (raw, and very compressible); a .pkg is xar
/// and may hold uncompressed payloads; a .zip carries uncompressed local
/// headers, a central directory, and often stored entries. Excluding these by
/// name would discard real wins that occur in the wild.
///
/// They are kept out of the *main* corpus only so they do not dilute it:
/// pooled in, low-yield content would mostly add wall-clock.
const SKIP_EXT: &[&str] = &[
    // Containers: contents decide, so always worth sampling.
    "zip", "jar", "gz", "bz2", "xz", "zst", "7z", "rar", "tar", "dmg", "pkg",
    // Image formats with older or partial compression, measurably non-zero.
    "png", "jpg", "jpeg", "gif",
    // Assumed low-yield, NOT yet measured: there was not enough of this
    // content in the corpus sources to test. Sampled rather than excluded so
    // the assumption gets checked the first time such a source is added.
    "mp4", "mov", "m4v", "mp3", "aac", "flac", "opus", "ogg", "webp",
];

/// Never sampled at all, not even into the precompressed kind. Every entry
/// here has been MEASURED at 0.00% recoverable by every engine, modern
/// entropy coders (JPEG XL's ANS, HEVC in HEIC/HEIF, brotli in WOFF2) leave
/// nothing behind, so these only add wall-clock.
///
/// Nothing goes in this list on the strength of its extension. If a format
/// has not been measured, it belongs in SKIP_EXT so that it is sampled and
/// the assumption gets tested.
const EXCLUDE_EXT: &[&str] = &["jxl", "heic", "heif", "avif", "woff", "woff2"];

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        // xorshift64*: deterministic across platforms, which is the point.
        // The same lockfile and seed must produce the same corpus anywhere.
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: u64) -> u64 {
        if n == 0 { 0 } else { self.next() % n }
    }
}

struct Candidate {
    path: PathBuf,
    len: u64,
    source: String,
    license: String,
    population: String,
    /// Path truncated to `--group-depth` components. Sampling is capped per
    /// group, not just per source, because a single documentation tree can
    /// otherwise swamp the corpus: rust-docs alone contributed 139 of 500
    /// segments of HTML on the first build, pushing text to 47% and
    /// inflating every headline ratio. A third-party app bundle, the thing
    /// this tier is a proxy for, is not 47% HTML.
    group: String,
    /// Already in a compressed container. Sampled into its own small kind
    /// rather than dropped: whether these are worth attempting is a
    /// measurement, and the answer decides whether skipping them by
    /// extension (what apfscompress does today) is leaving anything behind.
    precompressed: bool,
}

fn group_key(p: &Path, root: &Path, depth: usize) -> String {
    let rel = p.strip_prefix(root).unwrap_or(p);
    let mut it = rel.components();
    let mut parts = Vec::new();
    for _ in 0..depth {
        match it.next() {
            Some(c) => parts.push(c.as_os_str().to_string_lossy().to_string()),
            None => break,
        }
    }
    parts.join("/")
}

fn collect(dir: &Path, source: &Source, min_len: u64, depth: usize,
           root: &Path, out: &mut Vec<Candidate>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        let Ok(md) = e.metadata() else { continue };
        if md.is_symlink() {
            continue;
        }
        if md.is_dir() {
            collect(&p, source, min_len, depth, root, out);
        } else if md.len() >= min_len {
            let ext = p
                .extension()
                .map(|s| s.to_string_lossy().to_lowercase())
                .unwrap_or_default();
            if EXCLUDE_EXT.contains(&ext.as_str()) {
                continue;
            }
            let group = group_key(&p, root, depth);
            out.push(Candidate {
                path: p,
                len: md.len(),
                source: source.id.clone(),
                license: source.license.clone(),
                population: source.population.clone(),
                group,
                precompressed: SKIP_EXT.contains(&ext.as_str()),
            });
        }
    }
}

pub fn build(args: &[String]) -> R<()> {
    let target = num(args, "--target-bytes", 500 * 1024 * 1024)?;
    // Segments are ~1MB, not 64KB, on purpose. The bench measures 64KB blocks
    // (`--block`), so a 1MB segment is sixteen blocks of the size that
    // matters, and unlike a corpus of standalone 64KB files it gives the per-file
    // best-of-N rollup something to actually work with, since decmpfs picks
    // one algorithm per file rather than per block.
    let segment = num(args, "--segment", 1024 * 1024)?;
    // A handful of much larger segments, for the regression test that large
    // blocks are never worse than the same bytes chunked at 64KB. These are
    // a fixture set, not a benchmark population: the check is a paired
    // comparison on identical bytes, so a few dozen is plenty.
    let large_total = num(args, "--large", 40 * 1024 * 1024)?;
    let large_segment = 4 * 1024 * 1024;
    let precompressed_total = num(args, "--precompressed", 16 * 1024 * 1024)?;
    let seed = num(args, "--seed", 0x5A17_C0DE_1234_5678)?;
    // Path components that define a sampling group. 3 puts each source's
    // major subtree (rust-docs, rustc, VSCodium.app/Contents/Resources) in
    // its own bucket.
    let group_depth = num(args, "--group-depth", 3)?;
    // Share of one kind's budget any single group may supply.
    let group_share = num(args, "--group-share-pct", 12)?;

    let lock = load_lock()?;
    if lock.sources.is_empty() {
        return Err("nothing locked: run `corpus add` then `corpus fetch`".into());
    }

    let mut cands = Vec::new();
    for s in &lock.sources {
        let dir = cache_dir().join("unpacked.noindex").join(&s.id);
        if !dir.exists() {
            return Err(format!("{} not fetched: run `corpus fetch`", s.id));
        }
        collect(&dir, s, 64 * 1024, group_depth as usize, &dir, &mut cands);
    }
    if cands.is_empty() {
        return Err("no eligible files found in corpus/cache/unpacked.noindex".into());
    }
    cands.sort_by(|a, b| a.path.cmp(&b.path)); // stable order before shuffling
    eprintln!("{} candidate files", cands.len());

    let segs = segments_dir();
    let _ = fs::remove_dir_all(&segs);
    for k in ["main", "large", "precompressed"] {
        fs::create_dir_all(segs.join(k)).map_err(|e| e.to_string())?;
    }

    let mut rng = Rng(seed | 1);
    let mut manifest = String::from(
        "id\tbytes\tsegment_kind\tpopulation\tsource\tlicense\tsource_file\toffset\tsha256\n",
    );
    let mut written = 0u64;
    let mut n = 0usize;
    let mut per_source: std::collections::BTreeMap<String, u64> = Default::default();

    for (kind, budget, seg_len) in [
        ("main", target, segment),
        ("large", large_total, large_segment),
        // Small on purpose, and 256KB segments so ordinary photos qualify.
        ("precompressed", precompressed_total, 256 * 1024),
    ] {
        let want_pre = kind == "precompressed";
        let mut got = 0u64;
        let mut attempts = 0usize;
        // Cap per source so one big upstream tarball cannot dominate...
        let cap_per_source = budget / (lock.sources.len().max(1) as u64) * 2;
        // ...and per directory group so one subtree within a source cannot.
        let cap_per_group = budget * group_share / 100;
        let mut per_group: std::collections::BTreeMap<String, u64> = Default::default();

        while got < budget && attempts < cands.len() * 40 {
            attempts += 1;
            let c = &cands[rng.below(cands.len() as u64) as usize];
            if c.precompressed != want_pre {
                continue;
            }
            if c.len < seg_len {
                continue;
            }
            if kind == "main" {
                if *per_source.get(&c.source).unwrap_or(&0) > cap_per_source {
                    continue;
                }
                if *per_group.get(&c.group).unwrap_or(&0) >= cap_per_group {
                    continue;
                }
            }
            let offset = rng.below(c.len - seg_len + 1);
            let Ok(data) = read_at(&c.path, offset, seg_len) else { continue };
            if data.len() as u64 != seg_len {
                continue;
            }

            n += 1;
            let base = c
                .path
                .file_name()
                .map(|s| s.to_string_lossy().to_string())
                .unwrap_or_default();
            let safe: String = base
                .chars()
                .map(|ch| if ch.is_ascii_alphanumeric() || ch == '.' || ch == '-' { ch } else { '_' })
                .collect();
            let name = format!("{n:05}__{}__{safe}__off{offset}.bin", c.source);
            let out_path = segs.join(kind).join(&name);
            fs::write(&out_path, &data).map_err(|e| e.to_string())?;
            let digest = sha256(&out_path)?;

            let rel = c
                .path
                .strip_prefix(cache_dir().join("unpacked.noindex"))
                .unwrap_or(&c.path)
                .to_string_lossy()
                .to_string();
            manifest.push_str(&format!(
                "{n:05}\t{seg_len}\t{kind}\t{}\t{}\t{}\t{rel}\t{offset}\t{digest}\n",
                c.population, c.source, c.license
            ));

            got += seg_len;
            written += seg_len;
            *per_source.entry(c.source.clone()).or_default() += seg_len;
            *per_group.entry(c.group.clone()).or_default() += seg_len;
        }
        eprintln!("{kind:<6} {} MB in {} segments", got / 1_000_000, got / seg_len);
        if got < budget {
            eprintln!(
                "  (short of the {} MB target -- not enough distinct source files \
                 that large; add more sources)",
                budget / 1_000_000
            );
        }
    }

    fs::write(manifest_path(), manifest).map_err(|e| e.to_string())?;
    eprintln!("\n{} segments, {} MB total", n, written / 1_000_000);
    eprintln!("manifest: {}", manifest_path().display());
    for (s, b) in &per_source {
        eprintln!("  {s:<20} {} MB", b / 1_000_000);
    }
    Ok(())
}

/* ------------------------------------------------------------ system tier */

/// Tier B: macOS system content sampled directly off *this machine's* live
/// filesystem, never fetched by URL, never distributed (see `Source`'s
/// `population` doc above). Unlike Tier A there is no lockfile: the content
/// is whatever this Mac happens to have installed, which varies by machine,
/// by macOS build, and by day (Apple Intelligence assets, simulator runtime
/// count, dyld subcache count all drift). So this command is the recipe:
/// re-run it on any Mac and it re-measures and re-samples fresh, rather than
/// reproducing byte-identical output the way `corpus build` does.
///
/// Buckets mirror how the population was surveyed: dyld shared caches (the
/// actual LZBITMAP target), AssetsV2 (fixed-stride model/locale/dictionary
/// tables), and everything else under /System + /Library. Two exclusions
/// matter enough to hardcode: the iOS/watchOS Simulator runtime images
/// living inside AssetsV2 are Xcode developer content, not macOS, and
/// /Library/Developer is the same story for the "other" bucket.
struct SystemBucket {
    id: &'static str,
    roots: &'static [&'static str],
    exclude_prefixes: &'static [&'static str],
}

const SYSTEM_BUCKETS: &[SystemBucket] = &[
    SystemBucket {
        id: "dyld",
        roots: &[
            "/System/Volumes/Preboot/Cryptexes/OS/System/Library/dyld",
            "/System/Volumes/Preboot/Cryptexes/ExclaveOS/System/ExclaveKit/System/Library/dyld",
        ],
        exclude_prefixes: &[],
    },
    SystemBucket {
        id: "assets",
        roots: &["/System/Library/AssetsV2"],
        exclude_prefixes: &[
            "/System/Library/AssetsV2/com_apple_MobileAsset_iOSSimulatorRuntime",
            "/System/Library/AssetsV2/com_apple_MobileAsset_watchOSSimulatorRuntime",
        ],
    },
    SystemBucket {
        id: "other",
        roots: &["/System/Library", "/System/Applications", "/Library"],
        exclude_prefixes: &["/System/Library/AssetsV2", "/Library/Developer"],
    },
];

struct SysCandidate {
    path: PathBuf,
    len: u64,
    group: String,
}

/// Walks `dir`, never crossing onto a different filesystem than `root_dev`.
/// That single check is what keeps a walk rooted at /System/Library from
/// wandering into /System/Volumes/Preboot or /System/Volumes/Data, those
/// are separate APFS volumes mounted underneath, not part of the tree being
/// sampled, and buckets name them explicitly (as their own root) when their
/// content is actually wanted.
fn collect_system(
    dir: &Path,
    root_dev: u64,
    exclude_prefixes: &[&str],
    min_len: u64,
    depth: usize,
    group_root: &Path,
    out: &mut Vec<SysCandidate>,
) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        if exclude_prefixes.iter().any(|ex| p.starts_with(ex)) {
            continue;
        }
        let Ok(md) = e.metadata() else { continue };
        if md.is_symlink() {
            continue;
        }
        use std::os::unix::fs::MetadataExt;
        if md.dev() != root_dev {
            continue;
        }
        if md.is_dir() {
            collect_system(&p, root_dev, exclude_prefixes, min_len, depth, group_root, out);
        } else if md.len() >= min_len {
            if EXCLUDE_EXT.contains(
                &p.extension()
                    .map(|s| s.to_string_lossy().to_lowercase())
                    .unwrap_or_default()
                    .as_str(),
            ) {
                continue;
            }
            let group = group_key(&p, group_root, depth);
            out.push(SysCandidate { path: p, len: md.len(), group });
        }
    }
}

pub fn build_system(args: &[String]) -> R<()> {
    let target = num(args, "--target-bytes", 500 * 1024 * 1024)?;
    let segment = num(args, "--segment", 1024 * 1024)?;
    let seed = num(args, "--seed", 0x5A17_C0DE_1234_5678)?;
    let group_depth = num(args, "--group-depth", 3)?;
    // Looser than Tier A's 12%: these buckets have far fewer distinct
    // sources (a couple dozen dyld subcache files, not thousands), so a
    // tight cap would just fail to fill the budget.
    let group_share = num(args, "--group-share-pct", 25)?;

    eprintln!("scanning system content under {} bucket root(s): this walks real macOS \
               system directories and can take a few minutes\n",
              SYSTEM_BUCKETS.iter().map(|b| b.roots.len()).sum::<usize>());

    use std::os::unix::fs::MetadataExt;
    let mut buckets: Vec<(&str, Vec<SysCandidate>, u64)> = Vec::new();
    for b in SYSTEM_BUCKETS {
        let mut cands = Vec::new();
        for root_str in b.roots {
            let root = Path::new(root_str);
            let Ok(root_md) = fs::metadata(root) else {
                eprintln!("  {:<8} root missing or inaccessible, skipping: {root_str}", b.id);
                continue;
            };
            collect_system(root, root_md.dev(), b.exclude_prefixes, 64 * 1024,
                            group_depth as usize, root, &mut cands);
        }
        let total: u64 = cands.iter().map(|c| c.len).sum();
        eprintln!("  {:<8} {:>6} files  {:>7} MB", b.id, cands.len(), total / 1_000_000);
        buckets.push((b.id, cands, total));
    }

    let grand_total: u64 = buckets.iter().map(|(_, _, t)| *t).sum();
    if grand_total == 0 {
        return Err("no system content found: are these paths accessible from this \
                     environment? (SIP-sealed paths can be unreadable inside some sandboxes)"
            .into());
    }

    let segs = segments_dir().join("system");
    let _ = fs::remove_dir_all(&segs);
    fs::create_dir_all(&segs).map_err(|e| e.to_string())?;

    let mut rng = Rng(seed | 1);
    // No `bytes`/`license` columns here, unlike Tier A this content was
    // never fetched from anywhere with a license to record; `source_file` is
    // an absolute local path instead of one relative to corpus/cache.
    let mut manifest = String::from("id\tbytes\tbucket\tsource_file\toffset\tsha256\n");
    let mut n = 0usize;
    let mut written = 0u64;
    eprintln!();

    for (id, cands, total) in &buckets {
        if cands.is_empty() {
            continue;
        }
        // Proportional share of the overall budget, measured from what is
        // actually installed on this machine right now, not a hardcoded
        // percentage. A fixed split baked in on one Mac silently misrepresents
        // any machine whose dyld subcache count, simulator assets, or Apple
        // Intelligence downloads differ, which they routinely do.
        let budget = target * total / grand_total;
        let cap_per_group = (budget * group_share / 100).max(segment);
        let mut per_group: std::collections::BTreeMap<String, u64> = Default::default();
        let mut got = 0u64;
        let mut attempts = 0usize;
        while got < budget && attempts < cands.len().max(1) * 60 {
            attempts += 1;
            let c = &cands[rng.below(cands.len() as u64) as usize];
            if c.len < segment {
                continue;
            }
            if *per_group.get(&c.group).unwrap_or(&0) >= cap_per_group {
                continue;
            }
            let offset = rng.below(c.len - segment + 1);
            let Ok(data) = read_at(&c.path, offset, segment) else { continue };
            if data.len() as u64 != segment {
                continue;
            }

            n += 1;
            let base = c
                .path
                .file_name()
                .map(|s| s.to_string_lossy().to_string())
                .unwrap_or_default();
            let safe: String = base
                .chars()
                .map(|ch| if ch.is_ascii_alphanumeric() || ch == '.' || ch == '-' { ch } else { '_' })
                .collect();
            let name = format!("{n:05}__{id}__{safe}__off{offset}.bin");
            let out_path = segs.join(&name);
            fs::write(&out_path, &data).map_err(|e| e.to_string())?;
            let digest = sha256(&out_path)?;
            manifest.push_str(&format!(
                "{n:05}\t{segment}\t{id}\t{}\t{offset}\t{digest}\n",
                c.path.display()
            ));

            got += segment;
            written += segment;
            *per_group.entry(c.group.clone()).or_default() += segment;
        }
        eprintln!("{id:<8} {} MB in {} segments (target {} MB)",
                   got / 1_000_000, got / segment, budget / 1_000_000);
        if got < budget {
            eprintln!("  (short of target: not enough distinct large-enough files in this \
                        bucket on this machine)");
        }
    }

    let manifest_out = repo_root().join("corpus/manifest_system.tsv");
    fs::write(&manifest_out, manifest).map_err(|e| e.to_string())?;
    eprintln!("\n{} segments, {} MB total", n, written / 1_000_000);
    eprintln!("manifest: {}", manifest_out.display());
    eprintln!("\nmeasured population shares on this machine:");
    for (id, _, total) in &buckets {
        eprintln!("  {id:<8} {:5.1}%  ({} MB of {} MB scanned)",
                   100.0 * (*total as f64) / (grand_total as f64),
                   total / 1_000_000, grand_total / 1_000_000);
    }
    Ok(())
}

fn read_at(path: &Path, offset: u64, len: u64) -> R<Vec<u8>> {
    use std::io::{Read, Seek, SeekFrom};
    let mut f = fs::File::open(path).map_err(|e| e.to_string())?;
    f.seek(SeekFrom::Start(offset)).map_err(|e| e.to_string())?;
    let mut buf = vec![0u8; len as usize];
    f.read_exact(&mut buf).map_err(|e| e.to_string())?;
    Ok(buf)
}

/* ----------------------------------------------------------- manifest */

pub fn manifest(args: &[String]) -> R<()> {
    let kind = if has(args, "--large") {
        "large"
    } else if has(args, "--precompressed") {
        "precompressed"
    } else {
        "main"
    };
    // A stratified 1-in-10 sample, fixed by position so it is stable across
    // runs. Full-corpus passes take hours at the higher levels; this is the
    // subset to iterate against, not the one to publish from.
    let quick = has(args, "--quick");

    let dir = segments_dir().join(kind);
    let mut paths: Vec<PathBuf> = fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}; run `corpus build`", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "bin"))
        .collect();
    paths.sort();

    let out = std::io::stdout();
    let mut w = out.lock();
    for (i, p) in paths.iter().enumerate() {
        if quick && i % 10 != 0 {
            continue;
        }
        writeln!(w, "{}", p.display()).map_err(|e| e.to_string())?;
    }
    Ok(())
}

/* ------------------------------------------------------------- status */

pub fn status(_args: &[String]) -> R<()> {
    let lock = load_lock()?;
    println!("locked sources: {}", lock.sources.len());
    let mut locked_bytes = 0;
    for s in &lock.sources {
        let dl = cache_dir().join("downloads").join(&s.id);
        let unpacked = cache_dir().join("unpacked.noindex").join(&s.id);
        locked_bytes += s.bytes;
        println!(
            "  {:<20} {:>7} MB  {:<28} {:<10} {}",
            s.id,
            s.bytes / 1_000_000,
            s.license,
            s.population,
            match (dl.exists(), unpacked.exists()) {
                (_, true) => "extracted",
                (true, false) => "downloaded",
                _ => "not fetched",
            }
        );
    }
    println!("  {:<20} {:>7} MB total upstream", "", locked_bytes / 1_000_000);

    for kind in ["main", "large", "precompressed"] {
        let d = segments_dir().join(kind);
        let (n, bytes) = fs::read_dir(&d)
            .map(|it| {
                it.flatten()
                    .filter_map(|e| e.metadata().ok())
                    .fold((0u64, 0u64), |(n, b), m| (n + 1, b + m.len()))
            })
            .unwrap_or((0, 0));
        println!("segments/{kind:<6} {n:>6} segments  {:>6} MB", bytes / 1_000_000);
    }
    Ok(())
}
