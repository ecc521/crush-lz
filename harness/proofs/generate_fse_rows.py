#!/usr/bin/env python3
"""Extract shipping row arithmetic for scalar CBMC lemmas.

These lemmas establish actual packed-row ranges, not table-loop completion or
serialization. The runner checks the complete producer hash before building.
"""
from pathlib import Path
import hashlib
import argparse
import re


def generate(source):
    digest=hashlib.sha256(source.encode()).hexdigest()
    literal=source.index('int fse_init_decoder_table(')
    value=source.index('int fse_init_value_decoder_table(')
    fragments=[]
    for start in [literal,value]:
        a=source.index('    int k = __builtin_clz',start)
        b=source.index('    if (f <= fast_run)',a)
        fragments.append(source[a:b])
    literal_body,value_body=fragments
    value_tail=source[value:source.index('// Remove states from symbols',value)]
    # The scalar row lemma must remain tied to all four actual store sites.
    # Two fixed-width and two exact loops share these word/index expressions.
    for word,index,owned in [
        ('w0 + (uint64_t)j * step0','t + tp + j','j < j0'),
        ('w1 + (uint64_t)j * step1','t + tp + j0 + j','j < f - j0'),
    ]:
        pattern=(r'uint64_t e = '+re.escape(word)+r';\s*'
                 r'LZFSE_STORE_VALUE_ROW\('+re.escape(index)+r', e, '+
                 re.escape(owned)+r'\);')
        assert len(re.findall(pattern,value_tail))==2, 'value row store diverged from scalar lemma'
    assert '#define LZFSE_STORE_VALUE_ROW(dst, word, owned) memcpy((dst), &(word), 8)' in source
    for field in [
        'proof_dst->total_bits = (uint8_t)(word);',
        'proof_dst->value_bits = (uint8_t)((word) >> 8);',
        'proof_dst->delta = (int16_t)((word) >> 16);',
        'proof_dst->vbase = (int32_t)((word) >> 32);',
    ]:
        assert source.count(field)==1, 'proof store summary diverged from unpacking lemma'
    value_body=value_body.replace('symbol_vbits[i]','given_vbits').replace(
        'symbol_vbase[i]','given_base')
    return f'/* producer-sha256: {digest} */\n' + r'''
/* Generated by generate_fse_rows.py from shipping table row arithmetic. */
#include "proof.h"
#include "lzfse_fse.h"

static uint32_t literal_row(int nstates,int f,int i,int j)
__CPROVER_requires(nstates>8 && nstates<=1024 && (nstates & (nstates-1))==0)
__CPROVER_requires(f>=1 && f<=nstates)
__CPROVER_requires(i>=0 && i<=255 && j>=0 && j<f)
__CPROVER_assigns()
__CPROVER_ensures((__CPROVER_return_value & 0xff)<=10)
__CPROVER_ensures((__CPROVER_return_value >> 16) +
    (((uint32_t)1 << (__CPROVER_return_value & 0xff))-1)<(uint32_t)nstates)
__CPROVER_ensures(((__CPROVER_return_value >> 8)&0xff)==(uint32_t)i)
{
    int n_clz=__builtin_clz(nstates);
''' + literal_body + r'''
    return j<j0 ? w0+(uint32_t)j*step0 : w1+(uint32_t)(j-j0)*step1;
}

static uint64_t value_row(int nstates,int f,int j,uint8_t given_vbits,int32_t given_base)
__CPROVER_requires(nstates>8 && nstates<=1024 && (nstates & (nstates-1))==0)
__CPROVER_requires(f>=1 && f<=nstates && j>=0 && j<f)
__CPROVER_requires(given_vbits<=16 && given_base>=0 && given_base<=262139)
__CPROVER_assigns()
__CPROVER_ensures(((__CPROVER_return_value >> 8)&0xff)==given_vbits)
__CPROVER_ensures((__CPROVER_return_value >> 32)==(uint32_t)given_base)
__CPROVER_ensures((__CPROVER_return_value & 0xff)>=given_vbits)
__CPROVER_ensures((__CPROVER_return_value & 0xff)-given_vbits<=10)
__CPROVER_ensures(((__CPROVER_return_value >> 16)&0xffff)+
    (((uint32_t)1 << ((__CPROVER_return_value & 0xff)-given_vbits))-1)<(uint32_t)nstates)
{
    int n_clz=__builtin_clz(nstates);
''' + value_body + r'''
    return j<j0 ? w0+(uint64_t)j*step0 : w1+(uint64_t)(j-j0)*step1;
}

int nondet_int(void);
uint8_t nondet_u8(void);
void harness(void)
{
    int nstates=nondet_int(),f=nondet_int(),j=nondet_int();
#ifdef PROOF_VALUE_ROW
    uint8_t vbits=nondet_u8();
    int32_t base=nondet_int();
    uint64_t word=value_row(nstates,f,j,vbits,base);
    PROOF_REACHABLE(nstates==64 && vbits==8,"length-table width");
    PROOF_REACHABLE(nstates==256 && vbits==16,"distance-table width");
    PROOF_REACHABLE((word&0xff)==vbits,"zero state bits");
#else
    int symbol=nondet_int();
    uint32_t word=literal_row(nstates,f,symbol,j);
    PROOF_REACHABLE(nstates==1024 && (word&0xff)==10,"shipping literal state width");
    PROOF_REACHABLE(symbol==255,"upper literal symbol");
    PROOF_REACHABLE(f==nstates && j==nstates-1,"full-frequency final row");
#endif
}
'''


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--mutants',action='store_true')
    args=parser.parse_args()
    root=Path(__file__).resolve().parents[2]
    output=root/'harness/proofs/fse_table_rows.c'
    source=(root/'crates/crushlzfse/csrc/lzfse_fse.c').read_text()
    text=generate(source)
    if args.mutants:
        for old,new in [
            ('uint64_t e = w1 + (uint64_t)j * step1;',
             'uint64_t e = w1 + (uint64_t)(j + 1) * step1;'),
            ('LZFSE_STORE_VALUE_ROW(t + tp + j0 + j, e, j < f - j0);',
             'LZFSE_STORE_VALUE_ROW(t + tp + j0 + j + 1, e, j < f - j0);'),
            ('proof_dst->delta = (int16_t)((word) >> 16);',
             'proof_dst->delta = (int16_t)((word) >> 15);'),
        ]:
            assert old in source
            try:
                generate(source.replace(old,new,1))
            except AssertionError:
                pass
            else:
                raise AssertionError('row/store mutation escaped source guard')
        print('row/store/summary source mutations rejected')
        return
    if args.check:
        assert output.read_text()==text,'regenerate table-row lemmas after producer changes'
    else:
        output.write_text(text)


if __name__=='__main__':
    main()
