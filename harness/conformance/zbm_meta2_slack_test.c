struct slack_case {
    const char          *name;
    const unsigned char *stream;
    size_t               stream_len;
    const unsigned char *plain;
    size_t               plain_len;
    unsigned             slack;
};

static const struct slack_case cases[] = {
    { "1-byte meta_2 slack", zbm_slack_stream,  sizeof zbm_slack_stream,
      zbm_slack_plain,  sizeof zbm_slack_plain,  1 },
    { "3-byte meta_2 slack", zbm_slack3_stream, sizeof zbm_slack3_stream,
      zbm_slack3_plain, sizeof zbm_slack3_plain, 3 },
};

int main(void)
{
    static unsigned char dec[1 << 16];
    size_t i;
    int all_ok = 1;

    for (i = 0; i < sizeof cases / sizeof cases[0]; ++i) {
        const struct slack_case *c = &cases[i];
        size_t dlen = 0;
        int rc = crushlzbitmap_decode_buffer(dec, sizeof dec, c->stream, c->stream_len, &dlen);

        if (rc != 0) {
            printf("FAIL %s: decoder returned %d (a conforming Apple stream was refused)\n",
                   c->name, rc);
            all_ok = 0;
            continue;
        }
        if (dlen != c->plain_len) {
            printf("FAIL %s: decoded %zu bytes, expected %zu\n", c->name, dlen, c->plain_len);
            all_ok = 0;
            continue;
        }
        if (memcmp(dec, c->plain, c->plain_len) != 0) {
            size_t j = 0;
            while (j < c->plain_len && dec[j] == c->plain[j]) ++j;
            printf("FAIL %s: first differing byte at %zu (got 0x%02x, want 0x%02x)\n",
                   c->name, j, dec[j], c->plain[j]);
            all_ok = 0;
            continue;
        }
        printf("ok   %s: %zu bytes decoded, %u unused meta_2 byte(s) tolerated\n",
               c->name, dlen, c->slack);
    }

    /*
     * The other half of the rule. Overrunning an area is still a hard error,
     * and that is what separates an unused reservation from a damaged chunk.
     * Truncating the stream shortens every area it names, so the block
     * sequence outruns them and must be rejected rather than decoded.
     */
    {
        size_t cut;
        int rejected = 0, tried = 0;

        for (cut = 1; cut <= 24; ++cut) {
            size_t dlen = 0;
            int rc;

            ++tried;
            rc = crushlzbitmap_decode_buffer(dec, sizeof dec, zbm_slack_stream,
                                sizeof zbm_slack_stream - cut, &dlen);
            if (rc != 0)
                ++rejected;
        }
        if (tried && rejected == tried) {
            printf("ok   truncation: %d shortened stream(s) all rejected\n", tried);
        } else {
            printf("FAIL truncation: %d of %d shortened streams were accepted\n",
                   tried - rejected, tried);
            all_ok = 0;
        }
    }

    printf("\n%s\n", all_ok ? "ALL META_2 SLACK CASES PASSED"
                            : "*** AT LEAST ONE FAILURE ABOVE ***");
    return all_ok ? 0 : 1;
}
