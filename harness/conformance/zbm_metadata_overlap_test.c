static int check(const uint8_t *s, size_t n, const uint8_t *want, size_t size)
{
    uint8_t out[320];
    size_t got;
    memset(out, 0xa5, sizeof out);
    int rc = crushlzbitmap_decode_buffer(out, size, s, n, &got);
    if (rc || got != size || memcmp(out, want, size)) return 1;
    for (size_t i = size; i < sizeof out; ++i)
        if (out[i] != 0xa5) return 1;
    for (size_t cut = 0; cut < n; ++cut) {
        rc = crushlzbitmap_decode_buffer(out, sizeof out, s, cut, &got);
        if (rc == 0) return 1;
    }
    for (size_t cap = 0; cap < size; ++cap) {
        memset(out, 0xa5, sizeof out);
        rc = crushlzbitmap_decode_buffer(out, cap, s, n, &got);
        if (rc != CRUSHLZBITMAP_OUTPUT_TOO_SMALL || got != 0) return 1;
        for (size_t i = cap; i < sizeof out; ++i)
            if (out[i] != 0xa5) return 1;
    }
    return 0;
}

/* A literal consumes one input byte; a copy reads the produced byte eight
 * positions earlier. This model shares no decoder helpers or blend tables. */
static size_t block(uint8_t *want, size_t pos, uint8_t bitmap, unsigned *literal)
{
    for (unsigned i = 0; i < 8; ++i, ++pos)
        want[pos] = bitmap & (1u << i) ? (uint8_t)(0x41 + (*literal)++ % 26)
                                     : want[pos - 8];
    return pos;
}

int main(void)
{
    uint8_t want[312];
    for (size_t i = 0; i < 280; ++i) want[i] = (uint8_t)(1 + 7 * (i % 8));
    unsigned literal = 0;
    size_t pos = block(want, 280, 0xff, &literal);
    pos = block(want, pos, 0xff, &literal);
    pos = block(want, pos, 0x33, &literal);
    pos = block(want, pos, 0x33, &literal);
    if (check(meta3_two_nibble_control, sizeof meta3_two_nibble_control, want, pos) ||
        check(meta3_two_table_nibbles, sizeof meta3_two_table_nibbles, want, pos)) {
        fprintf(stderr, "selector/table overlap failed\n"); return 1;
    }
    literal = 0;
    pos = block(want, 160, 0, &literal);
    pos = block(want, pos, 0xde, &literal);
    if (check(meta2_overlap_control, sizeof meta2_overlap_control, want, pos) ||
        check(meta2_reads_meta3, sizeof meta2_reads_meta3, want, pos)) {
        fprintf(stderr, "bitmap/selector overlap failed\n"); return 1;
    }
    puts("metadata overlap controls, byte semantics, truncations and capacities passed");
    return 0;
}
