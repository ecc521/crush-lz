// D's FSE symbol, for D in [0, LZFSE_ENCODE_MAX_D_VALUE]: four bins per
// power of two of D + 4, each a quarter of it wide.
static inline uint32_t lzfse_d_symbol(uint32_t d) {
  uint32_t x = d + 4;
  uint32_t n = 31 - (uint32_t)__builtin_clz(x);
  return 4 * n - 8 + ((x >> (n - 2)) & 3);
}

